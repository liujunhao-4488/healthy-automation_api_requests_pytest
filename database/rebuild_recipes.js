/* ============================================================
   分组：确定 180 条菜谱的构成
   ------------------------------------------------------------
   按真实三餐比例：早餐 12 道、午餐 15 道、晚餐 15 道、加餐 8 道，
   循环铺满 180 条，每道菜会被复用多次但用不同分量组合，
   这样既保证每道菜的搭配合理，总量又能撑满 180 条。
   ============================================================ */

/** 轻微调整份量表：让同一道菜在多次出现时热量有合理差异 */
const SCALES = [0.9, 1.0, 1.1, 1.2]

function pickGrams(base, scale) {
  return Math.max(5, Math.round((base * scale) / 5) * 5)
}

function buildPlan() {
  const plan = []
  const groups = [
    { list: BREAKFAST, cat: '早餐', n: 48 },
    { list: LUNCH, cat: '午餐', n: 60 },
    { list: DINNER, cat: '晚餐', n: 57 },
    { list: SNACK, cat: '加餐', n: 15 }
  ]
  for (const g of groups) {
    for (let i = 0; i < g.n; i++) {
      const tpl = g.list[i % g.list.length]
      // 同一道菜第 2 轮起换份量，避免完全重复
      const round = Math.floor(i / g.list.length)
      const scale = SCALES[round % SCALES.length]
      plan.push({ tpl, cat: g.cat, scale, round })
    }
  }
  return plan
}

/** 按食材真名查营养，算出这道菜的合计热量与三大营养素 */
function calcNutrition(planItems, ingMap) {
  let kcal = 0, p = 0, c = 0, f = 0, fib = 0
  const items = []
  for (const [name, grams] of planItems) {
    const ing = ingMap.get(name)
    if (!ing) throw new Error('食材库中找不到：' + name)
    const g = grams
    const ratio = g / 100
    items.push({ ingredientId: ing.id, name, grams: g, unit: 'g' })
    kcal += (ing.cal || 0) * ratio
    p += (ing.pro || 0) * ratio
    c += (ing.carb || 0) * ratio
    f += (ing.fat || 0) * ratio
    fib += (ing.fib || 0) * ratio
  }
  return {
    items,
    totalCalories: Math.round(kcal * 100) / 100,
    protein: Math.round(p * 10) / 10,
    carbs: Math.round(c * 10) / 10,
    fat: Math.round(f * 10) / 10,
    fiber: Math.round(fib * 10) / 10
  }
}

/** 根据营养构成推荐适宜人群 */
function suitableFor(nut, cat) {
  const tags = []
  const pRatio = nut.totalCalories > 0 ? (nut.protein * 4) / nut.totalCalories : 0
  const fRatio = nut.totalCalories > 0 ? (nut.fat * 9) / nut.totalCalories : 0
  if (nut.totalCalories <= 450 && fRatio < 0.3) tags.push('减脂人群')
  if (pRatio >= 0.25 && nut.protein >= 20) tags.push('增肌人群')
  if (nut.fiber >= 4) tags.push('控糖人群')
  if (fRatio < 0.25) tags.push('控脂人群')
  if (!tags.length) tags.push('均衡维持人群')
  return tags.slice(0, 2).join('、')
}

function goalTypeOf(nut) {
  const pRatio = nut.totalCalories > 0 ? (nut.protein * 4) / nut.totalCalories : 0
  if (pRatio >= 0.28 && nut.protein >= 22) return '增肌'
  if (nut.totalCalories <= 450) return '减脂'
  return '维持'
}

function difficultyOf(tpl) {
  if (tpl.t <= 10) return '简单'
  if (tpl.t <= 25) return '中等'
  return '较难'
}

/** 创建时间：分散在过去一年内，不再机械递增 */
function createTimeOf(index, total) {
  const start = new Date('2025-11-01T08:00:00')
  const end = new Date('2026-10-20T20:00:00')
  const span = end.getTime() - start.getTime()
  // 用固定伪随机保证每次运行结果一致
  const seed = (index * 2654435761) % 1000 / 1000
  const t = new Date(start.getTime() + span * ((index + seed) / total))
  const p = (x) => String(x).padStart(2, '0')
  return `${t.getFullYear()}-${p(t.getMonth() + 1)}-${p(t.getDate())} ${p(8 + (index % 12))}:${p((index * 7) % 60)}:00`
}

async function main() {
  const conn = await mysql.createConnection(DB)
  console.log('已连接数据库 health_diet')

  // 1) 读食材
  const [ings] = await conn.query(
    "SELECT id, name, calories_per_100g cal, protein_per_100g pro, carbs_per_100g carb, fat_per_100g fat, fiber_per_100g fib FROM ingredient WHERE status=1 AND category<>'测试分类' ORDER BY id"
  )
  const ingMap = new Map()
  for (const i of ings) if (!ingMap.has(i.name)) ingMap.set(i.name, i)
  console.log(`食材 ${ingMap.size} 种（重名已取 id 最小者）`)

  // 2) 取出要重建的食谱 id
  const [rows] = await conn.query('SELECT id FROM recipe WHERE status=1 AND id>=600000 ORDER BY id')
  const ids = rows.map((r) => r.id)
  console.log(`待重建食谱 ${ids.length} 条`)

  const plan = buildPlan()
  if (plan.length !== ids.length) {
    throw new Error(`模板数量 ${plan.length} 与食谱数 ${ids.length} 不一致`)
  }

  // 3) 预演，不写库时只打印
  const preview = []
  for (let i = 0; i < ids.length; i++) {
    const { tpl, cat, scale } = plan[i]
    const scaled = tpl.ing.map(([n, g]) => [n, pickGrams(g, scale)])
    const nut = calcNutrition(scaled, ingMap)
    preview.push({
      id: ids[i],
      name: tpl.n + (plan[i].round > 0 ? '' : ''),
      category: cat,
      cuisine: tpl.c,
      time: tpl.t,
      ...nut
    })
  }

  // 输出统计
  const byCat = {}
  for (const p of preview) {
    byCat[p.category] = byCat[p.category] || []
    byCat[p.category].push(p.totalCalories)
  }
  console.log('\n=== 重建后热量分布 ===')
  for (const k of Object.keys(byCat)) {
    const arr = byCat[k]
    const avg = Math.round(arr.reduce((a, b) => a + b, 0) / arr.length)
    console.log(`  ${k}: ${arr.length} 条, 平均 ${avg} kcal, 区间 ${Math.round(Math.min(...arr))}-${Math.round(Math.max(...arr))}`)
  }

  console.log('\n=== 前 8 条样例 ===')
  for (const p of preview.slice(0, 8)) {
    console.log(`  [#${p.id}] ${p.name} | ${p.category} | ${Math.round(p.totalCalories)}kcal 蛋白${p.protein}g 纤维${p.fiber}g | ${p.items.map(i => i.name + i.grams + 'g').join(' + ')}`)
  }

  if (DRY) {
    console.log('\n[--dry] 仅预演，未写库')
    await conn.end()
    return
  }

  // 4) 写库
  console.log('\n开始写库...')
  await conn.beginTransaction()
  try {
    for (let i = 0; i < ids.length; i++) {
      const p = preview[i]
      const { tpl } = plan[i]
      const id = p.id

      // 更新食谱主体；营养值由配料实算，保证自洽
      await conn.query(
        `UPDATE recipe SET
           name=?, description=?, category=?, cuisine_type=?, cooking_time=?,
           difficulty=?, servings=1, total_calories=?, calories_per_serving=?,
           protein=?, carbs=?, fat=?, fiber=?, instructions=?, tips=?,
           suitable_for=?, goal_type=?, create_time=?, update_time=NOW()
         WHERE id=?`,
        [
          p.name,
          `${p.items.map(i => i.name).join('、')}，共 ${p.items.length} 种食材，约 ${Math.round(p.totalCalories)} kcal。`,
          p.category,
          p.cuisine,
          p.time,
          difficultyOf(tpl),
          p.totalCalories,
          p.totalCalories,
          p.protein,
          p.carbs,
          p.fat,
          p.fiber,
          JSON.stringify(tpl.steps),
          tpl.tip,
          suitableFor(p, p.category),
          goalTypeOf(p),
          createTimeOf(i, ids.length),
          id
        ]
      )

      // 重建配料：先删旧，再按新菜谱插入
      await conn.query('DELETE FROM recipe_ingredient WHERE recipe_id=?', [id])
      for (const it of p.items) {
        await conn.query(
          'INSERT INTO recipe_ingredient (recipe_id, ingredient_id, quantity, unit, is_optional, notes) VALUES (?,?,?,?,0,NULL)',
          [id, it.ingredientId, it.grams, 'g']
        )
      }
    }
    await conn.commit()
    console.log(`✅ 已更新 ${ids.length} 条食谱及其配料`)
  } catch (e) {
    await conn.rollback()
    console.error('❌ 回滚:', e.message)
    throw e
  }

  await conn.end()
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
