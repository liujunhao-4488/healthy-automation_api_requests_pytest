async function main() {
  const conn = await mysql.createConnection(DB)

  // 已有名字，避免重复
  const [exist] = await conn.query('SELECT name FROM ingredient')
  const existNames = new Set(exist.map((r) => r.name))

  const toInsert = []
  const skipped = []
  for (const it of ITEMS) {
    const [name] = it
    if (existNames.has(name)) { skipped.push(name); continue }
    toInsert.push(it)
  }

  console.log(`待新增 ${toInsert.length} 种食材`)
  if (skipped.length) console.log(`已存在跳过 ${skipped.length} 种：${skipped.join('、')}`)

  const byCat = {}
  for (const it of toInsert) (byCat[it[1]] = byCat[it[1]] || []).push(it[0])
  console.log('\n按分类：')
  for (const k of Object.keys(byCat)) console.log(`  ${k}: ${byCat[k].length} 种  ${byCat[k].join('、')}`)

  console.log('\n=== 样例 ===')
  for (const it of toInsert.slice(0, 5)) {
    console.log(`  ${it[0].padEnd(10)} ${it[1]}  ${it[3]}kcal 蛋白${it[4]}g 碳水${it[5]}g 脂肪${it[6]}g 钠${it[9]}mg`)
  }

  if (DRY) {
    console.log('\n[--dry] 仅预演，未写库')
    await conn.end()
    return
  }

  await conn.beginTransaction()
  try {
    const [[mx]] = await conn.query('SELECT MAX(id) mx FROM ingredient')
    let nextId = Math.max(500100, (mx.mx || 0) + 1)

    for (const it of toInsert) {
      const [name, cat, sub, kcal, p, c, f, fib, sug, na, gi, desc] = it
      await conn.query(
        `INSERT INTO ingredient
           (id, name, category, sub_category, calories_per_100g, protein_per_100g,
            carbs_per_100g, fat_per_100g, fiber_per_100g, sugar_per_100g,
            sodium_per_100g, gi_value, cholesterol_per_100g, description,
            image_url, status, create_time, update_time)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?,NULL,?,NULL,1,NOW(),NOW())`,
        [nextId++, name, cat, sub, kcal, p, c, f, fib, sug, na, gi, desc]
      )
    }
    await conn.commit()
    console.log(`\n✅ 已新增 ${toInsert.length} 种食材`)
  } catch (e) {
    await conn.rollback()
    console.error('❌ 回滚:', e.message)
    throw e
  }

  const [[stat]] = await conn.query(
    `SELECT COUNT(*) rows_cnt, COUNT(DISTINCT name) names
       FROM ingredient WHERE status=1 AND category<>'测试分类'`
  )
  console.log(`\n=== 结果 ===`)
  console.log(`  食材 ${stat.rows_cnt} 行 / ${stat.names} 个不同名称`)

  const [cats] = await conn.query(
    `SELECT category, COUNT(DISTINCT name) n FROM ingredient
      WHERE status=1 AND category<>'测试分类' GROUP BY category ORDER BY n DESC`
  )
  cats.forEach((r) => console.log(`  ${r.category}: ${r.n} 种`))

  await conn.end()
}

main().catch((e) => { console.error(e); process.exit(1) })
