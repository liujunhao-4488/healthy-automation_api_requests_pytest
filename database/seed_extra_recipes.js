/* 注意：模板里不允许出现库里没有的食材，也不允许 0g 占位。
   脚本启动时会逐道校验，任何一个不通过就整体退出，不写半成品数据。 */

const MEAL_DEFAULT_TIME = { 早餐: '08:00', 午餐: '12:30', 晚餐: '18:30', 加餐: '15:30' }

function calcNutrition(items, ingMap) {
  let kcal = 0, p = 0, c = 0, f = 0, fib = 0
  const rows = []
  for (const [name, grams] of items) {
    if (!(grams > 0)) continue
    const ing = ingMap.get(name)
    if (!ing) throw new Error('食材库中找不到：' + name)
    const r = grams / 100
    rows.push({ id: ing.id, name, grams, unit: 'g' })
    kcal += ing.cal * r
    p += ing.pro * r
    c += ing.carb * r
    f += ing.fat * r
    fib += ing.fib * r
  }
  return {
    items: rows,
    totalCalories: Math.round(kcal * 100) / 100,
    protein: Math.round(p * 10) / 10,
    carbs: Math.round(c * 10) / 10,
    fat: Math.round(f * 10) / 10,
    fiber: Math.round(fib * 10) / 10
  }
}

function suitableFor(nut) {
  const pRatio = nut.totalCalories > 0 ? (nut.protein * 4) / nut.totalCalories : 0
  const fRatio = nut.totalCalories > 0 ? (nut.fat * 9) / nut.totalCalories : 0
  const tags = []
  if (nut.totalCalories <= 450 && fRatio < 0.3) tags.push('减脂人群')
  if (pRatio >= 0.25 && nut.protein >= 20) tags.push('增肌人群')
  if (nut.fiber >= 4) tags.push('控糖人群')
  if (fRatio < 0.25) tags.push('控脂人群')
  if (!tags.length) tags.push('均衡维持人群')
  return tags.slice(0, 2).join('、')
}

function goalTypeOf(nut) {
  const pRatio = nut.totalCalories > 0 ? (nut.protein * 4) / nut.totalCalories : 0
  if (pRatio >= 0.28 && nut.protein >= 22) return '增肌'
  if (nut.totalCalories <= 450) return '减脂'
  return '维持'
}

function difficultyOf(minutes) {
  if (minutes <= 12) return '简单'
  if (minutes <= 25) return '中等'
  return '较难'
}

async function main() {
  const conn = await mysql.createConnection(DB)

  // 1) 读食材
  const [ings] = await conn.query(
    `SELECT id, name, calories_per_100g cal, protein_per_100g pro,
            carbs_per_100g carb, fat_per_100g fat, fiber_per_100g fib
       FROM ingredient WHERE status=1 AND category<>'测试分类' ORDER BY id`
  )
  const ingMap = new Map()
  for (const i of ings) if (!ingMap.has(i.name)) ingMap.set(i.name, i)
  console.log(`食材库可用 ${ingMap.size} 种`)

  // 2) 已有菜名，用于判重
  const [existing] = await conn.query('SELECT name FROM recipe WHERE status=1')
  const existingNames = new Set(existing.map((r) => r.name))
  console.log(`现有上架食谱 ${existing.length} 道`)

  // 3) 预校验并计算
  const plan = []
  const nameSeen = new Set()
  const errors = []

  for (const [name, cat, cuisine, minutes, items, steps, tip] of NEW_RECIPES) {
    if (existingNames.has(name)) { errors.push(`菜名与现有冲突：${name}`); continue }
    if (nameSeen.has(name)) { errors.push(`脚本内菜名重复：${name}`); continue }
    nameSeen.add(name)
    try {
      const nut = calcNutrition(items, ingMap)
      if (!nut.items.length) { errors.push(`${name} 无有效食材`); continue }
      plan.push({ name, cat, cuisine, minutes, items, steps, tip, nut })
    } catch (e) {
      errors.push(`${name}: ${e.message}`)
    }
  }

  if (errors.length) {
    console.error('\n❌ 校验未通过，未写入任何数据：')
    errors.forEach((e) => console.error('   - ' + e))
    await conn.end()
    process.exit(1)
  }

  // 4) 统计
  const byMeal = {}
  for (const p of plan) {
    ;(byMeal[p.cat] = byMeal[p.cat] || []).push(p.nut.totalCalories)
  }
  console.log(`\n待新增 ${plan.length} 道，餐次分布：`)
  for (const k of Object.keys(byMeal)) {
    const arr = byMeal[k]
    console.log(`  ${k}: ${arr.length} 道, 热量 ${Math.round(Math.min(...arr))}-${Math.round(Math.max(...arr))} kcal`)
  }

  console.log('\n=== 样例（前 6 道）===')
  for (const p of plan.slice(0, 6)) {
    console.log(`  ${p.name} | ${p.cat} | ${Math.round(p.nut.totalCalories)}kcal 蛋白${p.nut.protein}g | ${p.nut.items.map(i => i.name + i.grams + 'g').join(' + ')}`)
  }

  if (DRY) {
    console.log('\n[--dry] 仅预演，未写库')
    await conn.end()
    return
  }

  // 5) 写库
  await conn.beginTransaction()
  try {
    let maxId = 700000 // 新段，避开现有 100-199 与 600xxx
    const [[mx]] = await conn.query('SELECT MAX(id) mx FROM recipe')
    if (mx.mx && mx.mx >= maxId) maxId = mx.mx + 1

    let inserted = 0
    for (const p of plan) {
      const id = maxId++
      const nut = p.nut
      await conn.query(
        `INSERT INTO recipe
           (id, name, description, category, cuisine_type, cooking_time, difficulty, servings,
            total_calories, calories_per_serving, protein, carbs, fat, fiber,
            instructions, tips, image_url, creator_id, is_custom, score, score_count,
            view_count, collect_count, suitable_for, goal_type, status, create_time, update_time)
         VALUES (?,?,?,?,?,?,?,1,?,?,?,?,?,?,?,?,NULL,NULL,0,5,0,0,0,?,?,1,NOW(),NOW())`,
        [
          id, p.name,
          `${nut.items.map(i => i.name).join('、')}，共 ${nut.items.length} 种食材，约 ${Math.round(nut.totalCalories)} kcal。`,
          p.cat, p.cuisine, p.minutes, difficultyOf(p.minutes),
          nut.totalCalories, nut.totalCalories,
          nut.protein, nut.carbs, nut.fat, nut.fiber,
          JSON.stringify(p.steps), p.tip,
          suitableFor(nut), goalTypeOf(nut)
        ]
      )
      for (const it of nut.items) {
        await conn.query(
          `INSERT INTO recipe_ingredient (recipe_id, ingredient_id, quantity, unit, is_optional, notes)
           VALUES (?,?,?,?,0,NULL)`,
          [id, it.id, it.grams, 'g']
        )
      }
      inserted++
    }
    await conn.commit()
    console.log(`\n✅ 已新增 ${inserted} 道食谱及配料`)
  } catch (e) {
    await conn.rollback()
    console.error('❌ 回滚:', e.message)
    throw e
  }

  // 6) 结果
  const [[stat]] = await conn.query(
    `SELECT COUNT(*) total, COUNT(DISTINCT name) names FROM recipe WHERE status=1`
  )
  console.log(`\n=== 结果 ===`)
  console.log(`  上架食谱 ${stat.total} 道，不同菜名 ${stat.names} 个 —— ${stat.total === stat.names ? '✅ 无重名' : '❌ 有重名'}`)

  const [byCat] = await conn.query(
    `SELECT category, COUNT(*) n, ROUND(AVG(total_calories)) avg FROM recipe WHERE status=1 GROUP BY category`
  )
  byCat.forEach((r) => console.log(`  ${r.category}: ${r.n} 道，平均 ${r.avg} kcal`))

  await conn.end()
}

main().catch((e) => { console.error(e); process.exit(1) })
